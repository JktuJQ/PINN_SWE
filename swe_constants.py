import math

import torch

g = 9.81

# ----------------------------------------------------------------------------
# Задача Римана: прорыв плотины на влажном дне
# ----------------------------------------------------------------------------
H_LEFT = 2.0
H_RIGHT = 1.0
X_DAM = 0.0

# Максимальная скорость распространения возмущения — скорость головы волны
# разрежения, sqrt(g*h_L) = 4.43 м/с (скорость ударной волны 4.18 м/с меньше).
MAX_WAVE_SPEED = math.sqrt(g * max(H_LEFT, H_RIGHT))

# ----------------------------------------------------------------------------
# Область
# ----------------------------------------------------------------------------
# Важно: за t <= T_MAX возмущение не уходит дальше |x| = MAX_WAVE_SPEED*T_MAX
# = 4.43. Поэтому при |x| = 6 решение ТОЧНО равно начальному, и граничное
# условие Дирихле там не приближённое, а точное.
#
# Старое значение |x| <= 10 приводило к тому, что 56% области никогда не
# возмущается — сеть тратила на неё ёмкость и коллокационные точки впустую.
X_MIN, X_MAX = -6.0, 6.0
Y_MIN, Y_MAX = -6.0, 6.0
T_MIN, T_MAX = 0.0, 1.0

# Запас между фронтом самой быстрой волны и границей области
BOUNDARY_MARGIN = X_MAX - MAX_WAVE_SPEED * T_MAX

# ----------------------------------------------------------------------------
# Архитектура сети
# ----------------------------------------------------------------------------
HIDDEN = 128
DEPTH = 6                # число скрытых слоёв

# ВАЖНО: активации только гладкие (tanh). ReLU/Softplus в старой версии давали
# нулевую вторую производную и кусочно-постоянную первую — для невязки ФДУ это
# смертельно и давало видимые изломы в профиле скорости.

USE_FOURIER = False      # случайные фурье-признаки (помогают резким градиентам)
FOURIER_FEATURES = 64
FOURIER_SCALE = 2.0

H_FLOOR = 1e-3           # h = H_FLOOR + softplus(...) — положительность по построению
H_INIT = 1.5             # начальный уровень h (смещение последнего слоя)

# ----------------------------------------------------------------------------
# Обучение
# ----------------------------------------------------------------------------
ADAM_EPOCHS = 8000
LBFGS_STEPS = 400
LR = 2e-3
LR_FINAL = 1e-5          # экспоненциальный спад LR к концу обучения Adam

# Число точек каждого типа
N_F = 8192               # внутри области (невязка ФДУ)
N_IC = 2048              # начальные условия
N_BC = 1024              # на каждую пару границ (x-стенки и y-стенки)

# ----------------------------------------------------------------------------
# Искусственная вязкость (метод исчезающей вязкости)
# ----------------------------------------------------------------------------
# Гладкая сеть принципиально не может представить разрыв. Но вязкое уравнение
# u_t + f(u)_x = nu*u_xx имеет ГЛАДКОЕ решение с толщиной фронта O(nu), которое
# сеть представить может. Отжигая nu вниз, получаем всё более резкий фронт,
# сходящийся к энтропийному решению.
VISC_START = 0.10
VISC_END = 0.005
VISC_ANNEAL_FRAC = 0.6   # к 60% эпох Adam достигаем VISC_END

# ----------------------------------------------------------------------------
# Учебный план по времени (time marching curriculum)
# ----------------------------------------------------------------------------
# Гиперболические задачи переносят информацию вперёд по времени. Обучать сразу
# на всём [0, T] — значит требовать от сети угадать позднее состояние раньше,
# чем она выучила раннее. Поэтому наращиваем горизонт постепенно.
CURRICULUM_STAGES = 4
CURRICULUM_FRAC = 0.4    # первые 40% эпох Adam уходят на наращивание горизонта

# Причинностное взвешивание (Wang, Sankaran, Perdikaris 2022):
# вес невязки в момент t гасится, пока не мала невязка при всех t' < t.
N_TIME_BINS = 16
CAUSAL_EPS = 2.0

# ----------------------------------------------------------------------------
# Выборка коллокационных точек
# ----------------------------------------------------------------------------
CONE_FRAC = 0.5          # доля точек, сосредоточенных в конусе влияния разрыва
CONE_MARGIN = 0.5

RAR_EVERY = 500          # адаптивное добавление точек по невязке
RAR_POOL = 40000         # размер пула-кандидата
RAR_KEEP = 2048          # сколько точек с наибольшей невязкой оставить

# ----------------------------------------------------------------------------
# Веса компонент функции потерь
# ----------------------------------------------------------------------------
W_PDE = 1.0
W_IC = 10.0
W_BC = 10.0

# Автобалансировка весов по нормам градиентов (Wang et al. 2021) — снимает
# необходимость подбирать веса вручную.
ADAPTIVE_WEIGHTS = True
ADAPT_EVERY = 250
ADAPT_ALPHA = 0.9        # сглаживание EMA
W_MIN, W_MAX = 1e-2, 1e4

# ----------------------------------------------------------------------------
# Численный метод (HLL)
# ----------------------------------------------------------------------------
CFL = 0.45
HLL_NX = 200
HLL_NY = 200

# ----------------------------------------------------------------------------
SEED = 0

def _pick_device():
    """Выбор устройства; можно переопределить переменной среды SWE_DEVICE.

    Замер на Apple M-series (полный шаг обучения, N_F=8192, с прогревом):
        CPU  499 мс/шаг      MPS  249 мс/шаг
    Расхождение невязки между CPU и MPS на одних весах ~5e-7 (float32), т.е.
    MPS численно безопасен. Важно: первые вызовы на MPS медленные (компиляция
    ядер), поэтому мерить скорость нужно только после прогрева.
    """
    import os
    forced = os.environ.get("SWE_DEVICE")
    if forced:
        return torch.device(forced)
    if torch.cuda.is_available():
        return torch.device("cuda")
    if torch.backends.mps.is_available():
        return torch.device("mps")
    return torch.device("cpu")

DEVICE = _pick_device()

MODEL_PATH = "data/pinn_swe.model"


def check_domain_is_large_enough():
    """Проверяет, что за T_MAX волны не доходят до границы (иначе BC неточное)."""
    reach = MAX_WAVE_SPEED * T_MAX
    ok = reach < min(abs(X_MIN - X_DAM), abs(X_MAX - X_DAM))
    return ok, reach
